#!/usr/bin/env node
/**
 * Generate docs/accuracy.md and docs/catalog.md from the extraction report,
 * the reference figures and the files in dist/.
 *
 *   node scripts/build/report.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, readCSV, writeFile, polygonsOf, formatBytes } from './lib.js';
import { toUTM } from '../../src/utm.js';
import catalog from '../../src/catalog.js';

const report = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/source/extract-report.json'), 'utf8'));
const munReport = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/source/municipalities-report.json'), 'utf8'));
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'dist/manifest.json'), 'utf8'));
const D = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, 'dist/data', `${p}.json`), 'utf8'));
const n = (x, d = 0) => Number(x).toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
const pct = (x, d = 2) => `${x >= 0 ? '+' : ''}${(x * 100).toFixed(d)} %`;
const GENERATED = '<!-- Generated by scripts/build/report.js — do not edit by hand. -->';

// ------------------------------------------------------------------ helpers
function geojson(p, lod) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, 'dist/geojson', `tunisia-${p}-${lod}.geojson`), 'utf8'));
}
/** Planar UTM area (km²) and vertex count of a WGS84 geometry — used to compare levels of detail. */
function measure(geometry) {
  let area = 0, vertices = 0;
  for (const rings of polygonsOf(geometry)) rings.forEach((ring, i) => {
    const pts = ring.map(toUTM);
    let s = 0;
    for (let a = 0, b = pts.length - 1; a < pts.length; b = a++) s += (pts[b][0] - pts[a][0]) * (pts[b][1] + pts[a][1]);
    area += (i === 0 ? 1 : -1) * Math.abs(s / 2);
    vertices += ring.length;
  });
  return { area: area / 1e6, vertices };
}

// ------------------------------------------------------------------ accuracy.md
{
  const gov = D('governorates');
  const published = Object.fromEntries(readCSV(path.join(ROOT, 'data/reference/governorate-areas.csv')).map((r) => [r.id, Number(r.area_km2_published)]));
  const country = D('country')[0];
  const t = report.topology;
  const src = report.source;
  const corrections = report.corrections;
  const byType = (type) => corrections.filter((c) => c.type === type);
  const delName = Object.fromEntries(D('delegations').map((d) => [d.id, d.name_fr]));
  const govName = Object.fromEntries(gov.map((g) => [g.id, g.name_fr]));

  const lines = [GENERATED, '', '# Accuracy report', ''];
  lines.push(
    `This report is regenerated with every build. It documents where the geometry comes from, every correction applied to the source data,`,
    `and the checks that the published maps pass. Source: OpenStreetMap extract of **${src.osm_date}**` +
      (src.osm_timestamp ? ` (replication timestamp \`${src.osm_timestamp}\`${src.sha256 ? `, SHA-256 \`${src.sha256.slice(0, 16)}…\`` : ''})` : '') + '.',
    '',
    '## At a glance',
    '',
    '| Check | Result |',
    '| --- | --- |',
    `| Land area of Tunisia (ellipsoidal) | **${n(country.area_km2)} km²** (CIA World Factbook: 155,360 km² of land, ${pct(country.area_km2 / 155360 - 1)}) |`,
    `| Governorates | **${gov.length}** / 24 (ISO 3166-2:TN) |`,
    `| Delegations | **${D('delegations').length}** / 279 (INS 2024 nomenclature) |`,
    `| Sectors (imadas) | **${n(D('sectors').length)}** (OSM, INS 2014 geocodes) |`,
    `| Municipalities (baladiyat) | **${D('municipalities').length}** of 350, covering ${(munReport.topology.coverage * 100).toFixed(1)} % of the land ([details](#municipalities-baladiyat)) |`,
    `| Overlap between units | **${t.overlap_km2.toFixed(6)} km²** |`,
    `| Land not covered by any unit | **${(t.uncovered_km2 * 1e6).toFixed(0)} m²** (floating-point noise) |`,
    `| Sum of children = parent area | exact at every level (additive area formula) |`,
    `| Census population, governorates | ${n(country.population_2024)} inhabitants (RGPH 2024), equal to the national total |`,
    `| Projection helper vs PROJ | < 1 mm (tested) |`,
    '',
    '## Method in one paragraph',
    '',
    'Every governorate, delegation and sector boundary from OpenStreetMap is noded into **one planar set of faces**, so all levels share',
    'exactly the same edges. Each face is labelled with its governorate, delegation and sector; conflicts are resolved by documented',
    'rules; areas that a lower level leaves uncovered (inland lakes and sebkhas that OSM excludes from delegations) are split between',
    'neighbouring units of the same parent by nearest-boundary allocation. Units are then dissolved from these faces, which guarantees',
    'zero gaps and zero overlaps, and identical shared borders at every level. See [methodology.md](methodology.md).',
    '',
    '## Governorate areas vs published figures',
    '',
    'Published areas (Ministry of Industry, compiled by Wikipedia) include inland water and come from older surveys; OSM-derived areas',
    'follow the precise coastline. Lagoons open to the sea (Bizerte, Ghar El Melh, Tunis, El Bibane) are water and are excluded.',
    '',
    '| Governorate | Map Tunisia (km²) | Published (km²) | Difference |',
    '| --- | ---: | ---: | ---: |',
  );
  let absErr = [];
  for (const g of gov) {
    const p = published[g.id];
    const d = Number(g.area_km2) / p - 1;
    absErr.push(Math.abs(d));
    lines.push(`| ${g.name_fr} (${g.id}) | ${n(g.area_km2)} | ${n(p)} | ${pct(d, 1)} |`);
  }
  absErr.sort((a, b) => a - b);
  lines.push(
    `| **Tunisia** | **${n(country.area_km2)}** | **${n(Object.values(published).reduce((a, b) => a + b, 0))}** | |`,
    '',
    `Median absolute difference: **${(absErr[Math.floor(absErr.length / 2)] * 100).toFixed(1)} %**.`,
    '',
    '## Levels of detail: shape fidelity',
    '',
    'Area change of the governorates relative to the full-precision geometry, and vertex counts.',
    '',
    '| Level | Tolerance | Vertices (governorates) | Max area change of a governorate | Total area change |',
    '| --- | ---: | ---: | ---: | ---: |',
  );
  const full = Object.fromEntries(geojson('governorates', 'full').features.map((f) => [f.id, measure(f.geometry)]));
  const fullTotal = Object.values(full).reduce((s, m) => s + m.area, 0);
  for (const lod of catalog.lods) {
    const feats = geojson('governorates', lod.id).features;
    let maxD = 0, vtx = 0, total = 0;
    for (const f of feats) {
      const m = measure(f.geometry);
      vtx += m.vertices; total += m.area;
      maxD = Math.max(maxD, Math.abs(m.area / full[f.id].area - 1));
    }
    lines.push(`| ${lod.id} | ${lod.toleranceMeters ? `${n(lod.toleranceMeters)} m` : '—'} | ${n(vtx)} | ${(maxD * 100).toFixed(2)} % | ${pct(total / fullTotal - 1, 3)} |`);
  }

  lines.push('', '## Corrections applied to OpenStreetMap', '', 'Every correction comes from [`scripts/extract/corrections.json`](../scripts/extract/corrections.json) or from an automatic rule, and is logged by the extractor.', '');
  const nd = byType('new_delegation');
  if (nd.length) {
    lines.push(
      `### ${nd.length} delegations created after 2014, rebuilt from their imadas`,
      '',
      'OpenStreetMap still follows the INS 2014 nomenclature (264 delegations). The delegations created since are rebuilt by regrouping the OSM',
      'sectors (imadas) that compose them, as listed by the electoral authority ISIE (2023 local elections and 2025 administrative circonscription maps).',
      '',
      '| Delegation | Governorate | Formed from | Imadas | Confidence |',
      '| --- | --- | --- | ---: | --- |',
    );
    for (const c of nd) lines.push(`| ${c.name} (\`${c.id}\`) | ${govName[c.governorate]} | ${c.formed_from.join(', ')} | ${c.sectors} | ${c.confidence} |`);
    lines.push('');
  }
  const other = [
    ...byType('drop_relation').map((c) => `Dropped OSM relation ${c.osm_id} (${c.name}): ${c.reason}`),
    ...byType('delegation_code').map((c) => `Delegation relation ${c.osm_id} has no INS code in OSM; assigned **${c.code}**. ${c.reason}`),
    ...byType('sector_reassignment').map((c) => `Sector \`${c.sector}\` (${c.name}) moved from ${delName[c.from_delegation] || c.from_delegation} to **${delName[c.to_delegation] || c.to_delegation}**. ${c.reason}`),
    ...byType('governorate_boundary_conflict').map((c) => `${c.area_km2.toFixed(2)} km² moved from ${govName[c.from_governorate]} to **${govName[c.to_governorate]}** (inside ${delName[c.delegation] || c.delegation}). ${c.reason}`),
    ...byType('add_islets').map((c) => `${c.count} islets (${c.area_km2} km² in total) mapped only as coastline were added and assigned to the nearest unit.`),
  ];
  const names = byType('name_override');
  if (names.length) {
    other.push(
      `${names.length} sector names corrected after the ISIE circonscription maps — swapped or duplicated names and Arabic typos: ` +
        names.map((c) => `\`${c.id}\` → ${[c.name_ar, c.name_fr].filter(Boolean).join(' / ')}`).join('; ') + '.',
    );
  }
  if (other.length) lines.push('### Other corrections', '', ...other.map((s) => `- ${s}`), '');
  const gaps = byType('delegation_gap_allocation').sort((a, b) => b.area_km2 - a.area_km2);
  lines.push(
    '### Inland water allocated to delegations',
    '',
    `OSM delegations and sectors leave out ${n(report.gaps.delegation_level_km2, 0)} km² of inland water bodies and slivers (${report.gaps.delegation_level_components} pieces)`,
    'that the governorates include. They are split between the neighbouring delegations of the same governorate. The largest:',
    '',
    '| Area (km²) | Location (lon, lat) | Governorate | Split between |',
    '| ---: | --- | --- | --- |',
    ...gaps.slice(0, 15).map((g) => `| ${g.area_km2.toFixed(1)} | ${g.at[0]}, ${g.at[1]} | ${govName[g.parent]} | ${g.split_between.map((d) => delName[d] || d).join(', ')} |`),
    '',
  );
  lines.push('## Known issues in the source data', '', 'Warnings raised by the extractor. They do not break the nesting, but you may want to know about them.', '');
  const preSplit = report.warnings.filter((w) => w.includes('code from before a delegation split'));
  const islands = report.warnings.filter((w) => w.includes('(islands or exclaves)'));
  for (const w of report.warnings.filter((w) => !preSplit.includes(w) && !islands.includes(w))) lines.push(`- ${w}`);
  if (preSplit.length) {
    lines.push(`- ${preSplit.length} sectors of delegations created after 2014 still carry the INS geocode of their former delegation ` +
      `(sector ids keep these codes for stability): ${preSplit.map((w) => `\`${w.split(' ')[0]}\``).join(', ')}.`);
  }
  if (islands.length) {
    lines.push(`- ${islands.length} delegations consist of several parts because of islands: ` +
      islands.map((w) => { const id = w.split(' ')[0]; return `${delName[id] || id}`; }).join(', ') + '.');
  }
  {
    const mt = munReport.topology;
    const mun = D('municipalities');
    const munName = Object.fromEntries(mun.map((m) => [m.id, m.name_fr]));
    // Names that look wrong in OSM, listed while the relation still carries that name.
    const suspect = [
      ['municipality-7209947', 'Fouchana', 'covers the Naassen, Chebeda and Douar Elhouch sectors, so it is probably the Naassen municipality'],
      ['municipality-7304421', 'Ben Arous', 'covers La Nouvelle Médina and El Yasminet, next to the other Ben Arous relation'],
    ].filter(([id, name]) => munName[id] === name);
    lines.push(
      '', '## Municipalities (baladiyat)', '',
      'Municipalities do not nest in delegations or sectors, so they are a partition of their own: OpenStreetMap relations tagged',
      '`boundary=municipality`, clipped to the land above, with no geometry added. Where two relations overlap, the overlap goes to the',
      'smaller one. Land that no OSM municipality covers is left uncovered and drawn as a light base under the units in every SVG.', '',
      '| Check | Result |', '| --- | --- |',
      `| Municipalities | **${mun.length}** in ${munReport.counts.governorates} governorates (350 in the 2016 division) |`,
      `| Land covered | **${n(mt.covered_km2)} km²** of ${n(mt.land_area_km2)} km² (${(mt.coverage * 100).toFixed(2)} %) |`,
      `| Land not in any municipality | ${n(mt.uncovered_km2)} km² in ${mt.uncovered_pieces} pieces |`,
      `| Overlap between municipalities | **${mt.overlap_km2.toFixed(6)} km²** after resolving ${munReport.corrections.filter((c) => c.type === 'overlap_to_smaller').length} overlapping relation(s) |`,
      `| Outside the land | ${mt.outside_land_km2.toFixed(6)} km² |`,
      `| Invalid geometries | ${mt.invalid_geometries} |`,
      `| Spread over several delegations | ${mt.across_delegations} municipalities (why they cannot nest) |`,
      '',
    );
    for (const c of munReport.corrections.filter((c) => c.type === 'overlap_to_smaller')) {
      lines.push(`- Relation ${c.osm_id} (${c.name}) overlapped ${c.given_to.map((w) => `relation ${w.osm_id} (${w.name})`).join(', ')} by ${c.area_km2} km²; the overlap went to the smaller one.`);
    }
    for (const w of munReport.warnings) lines.push(`- ${w}.`);
    for (const [id, name, why] of suspect) lines.push(`- \`${id}\` is named ${name} in OSM but ${why}. The OSM name is kept until it is corrected there.`);
    lines.push(
      '', 'Largest land areas outside any OSM municipality. Some are inland water that the municipal boundaries leave out (for example',
      'Sebkhet Sidi El Hani, Garaet Ichkeul, Sebkhet Ariana and Sebkhet Sejoumi); the large pieces in Sidi Bouzid and Sfax are land',
      'that OpenStreetMap does not yet assign to any municipality:', '',
      '| Area (km²) | Location (lon, lat) | Governorate | Delegations |', '| ---: | --- | --- | --- |',
      ...munReport.uncovered.map((u) => `| ${u.area_km2.toFixed(1)} | ${u.at[0]}, ${u.at[1]} | ${govName[u.governorate]} | ${u.delegations.map((d) => delName[d] || d).join(', ')} |`),
      '',
    );
  }
  lines.push('', 'Found an error? Please [open a data issue](https://github.com/Alaa-Taieb/map-tunisia/issues/new?template=data-error.yml).', '');
  writeFile(path.join(ROOT, 'docs/accuracy.md'), lines.join('\n'));
  console.log('docs/accuracy.md');
}

// ------------------------------------------------------------------ reference.md
{
  const reg = D('regions'), dis = D('districts'), gov = D('governorates'), del = D('delegations'), sec = D('sectors');
  const name = Object.fromEntries([...reg, ...dis, ...gov].map((r) => [r.id, r.name_en || r.name_fr]));
  const secCount = {};
  for (const s of sec) secCount[s.delegation] = (secCount[s.delegation] || 0) + 1;
  const lines = [GENERATED, '', '# Reference tables', '',
    'Every unit of the coarser partitions and the municipalities, with identifiers, names and figures. Sectors (imadas) are too many for a page — use',
    '[`dist/data/sectors.csv`](../dist/data/sectors.csv). Areas are ellipsoidal; populations are INS census counts (RGPH 2014 and 2024).', '',
    '- [Economic regions](#economic-regions)', '- [Districts (2023)](#districts-2023)', '- [Governorates](#governorates)', '- [Delegations](#delegations)', '- [Municipalities](#municipalities)', '',
    '## Economic regions', '', '| id | Name (EN) | Nom (FR) | الاسم | Governorates | Population 2024 | Area (km²) |', '| --- | --- | --- | --- | --- | ---: | ---: |'];
  for (const r of reg) lines.push(`| \`${r.id}\` | ${r.name_en} | ${r.name_fr} | ${r.name_ar} | ${r.governorates.split(' ').join(', ')} | ${n(r.population_2024)} | ${n(r.area_km2)} |`);
  lines.push('', '## Districts (2023)', '', 'Created by Decree 2023-589 of 21 September 2023 for the National Council of Regions and Districts.', '',
    '| id | Name | الاسم | Governorates | Population 2024 | Area (km²) |', '| --- | --- | --- | --- | ---: | ---: |');
  for (const r of dis) lines.push(`| \`${r.id}\` | ${r.name_en} — ${r.name_fr} | ${r.name_ar} | ${r.governorates.split(' ').map((g) => name[g]).join(', ')} | ${n(r.population_2024)} | ${n(r.area_km2)} |`);
  lines.push('', '## Governorates', '', '`id` is the ISO 3166-2 code; `INS` is the code used by the Institut National de la Statistique (prefix of delegation and sector codes).', '',
    '| id | INS | Name (EN) | Nom (FR) | الاسم | Capital | Region | District | Delegations | Population 2024 | Area (km²) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | ---: | ---: | ---: |');
  for (const g of gov) {
    const nd = del.filter((d) => d.governorate === g.id).length;
    lines.push(`| \`${g.id}\` | ${g.ins_code} | ${g.name_en} | ${g.name_fr} | ${g.name_ar} | ${g.capital_fr} | ${name[g.region]} | ${g.district.replace('district-', '')} | ${nd} | ${n(g.population_2024)} | ${n(g.area_km2)} |`);
  }
  lines.push('', '## Delegations', '', `${del.length} delegations (INS 2024 nomenclature). Rows marked ✦ were created after 2014 and are rebuilt from their imadas.`, '');
  for (const g of gov) {
    lines.push(`### ${g.name_fr} · ${g.name_ar} (${g.id})`, '', '| id | Nom (FR) | الاسم | Sectors | Population 2024 | Area (km²) |', '| --- | --- | --- | ---: | ---: | ---: |');
    for (const d of del.filter((x) => x.governorate === g.id)) {
      const star = d.source && d.source !== 'osm' ? ' ✦' : '';
      lines.push(`| \`${d.id}\` | ${d.name_fr}${star} | ${d.name_ar} | ${secCount[d.id] || 0} | ${d.population_2024 ? n(d.population_2024) : '—'} | ${n(d.area_km2, 1)} |`);
    }
    lines.push('');
  }
  const govOf = Object.fromEntries(gov.map((g) => [g.id, g.name_fr]));
  const mun = D('municipalities').sort((a, b) => a.governorate.localeCompare(b.governorate) || a.name_fr.localeCompare(b.name_fr, 'fr'));
  lines.push('## Municipalities', '', `${mun.length} municipalities (baladiyat) mapped in OpenStreetMap, a partition of its own that does not nest in delegations.`,
    'The `id` carries the OSM relation number. Coverage and known issues: [accuracy report](accuracy.md#municipalities-baladiyat).', '',
    '| id | Nom (FR) | الاسم | Governorate | Area (km²) |', '| --- | --- | --- | --- | ---: |');
  for (const m of mun) lines.push(`| \`${m.id}\` | ${m.name_fr} | ${m.name_ar} | ${govOf[m.governorate]} | ${n(m.area_km2, 1)} |`);
  lines.push('');
  writeFile(path.join(ROOT, 'docs/reference.md'), lines.join('\n'));
  console.log('docs/reference.md');
}

// ------------------------------------------------------------------ catalog.md
{
  const lines = [GENERATED, '', '# File catalog', '', `Every file in \`dist/\`, generated from the OpenStreetMap extract of **${manifest.osm_date}**.`, ''];
  const svg = manifest.files.filter((f) => f.type === 'svg');
  const total = (type) => manifest.files.filter((f) => f.type === type).reduce((s, f) => s + f.bytes, 0);
  lines.push(
    `**${svg.length} SVG files** (${formatBytes(total('svg'))}) · **${manifest.files.filter((f) => f.type === 'geojson').length} GeoJSON** (${formatBytes(total('geojson'))}) · ` +
      `**${manifest.files.filter((f) => f.type === 'topojson').length} TopoJSON** (${formatBytes(total('topojson'))}) · attribute tables in \`dist/data/\`.`,
    '',
  );
  const modes = catalog.modes.map((m) => m.id);
  for (const p of catalog.partitions) {
    lines.push(`## ${p.title} — ${n(p.count)} unit${p.count > 1 ? 's' : ''}`, '', `| Level | ${modes.join(' | ')} | GeoJSON | TopoJSON |`, `| --- | ${modes.map(() => '---:').join(' | ')} | ---: | ---: |`);
    for (const lod of p.lods) {
      const cells = modes.map((m) => {
        const f = svg.find((x) => x.partition === p.id && x.lod === lod && x.mode === m);
        return f ? `[${formatBytes(f.bytes)}](../${f.path})` : '·';
      });
      const gj = manifest.files.find((x) => x.type === 'geojson' && x.partition === p.id && x.lod === lod);
      const tj = manifest.files.find((x) => x.type === 'topojson' && x.partition === p.id && x.lod === lod);
      lines.push(`| **${lod}** | ${cells.join(' | ')} | [${formatBytes(gj.bytes)}](../${gj.path}) | [${formatBytes(tj.bytes)}](../${tj.path}) |`);
    }
    lines.push('', `Attributes: [\`dist/data/${p.id}.csv\`](../dist/data/${p.id}.csv) · [\`dist/data/${p.id}.json\`](../dist/data/${p.id}.json)`, '');
  }
  lines.push('`·` = not generated for this combination (e.g. labels on the full level of detail, or nested borders for partitions without a parent).', '');
  writeFile(path.join(ROOT, 'docs/catalog.md'), lines.join('\n'));
  console.log('docs/catalog.md');
}
